"""Validate a sign-holder configuration and prepare an OpenSCAD model."""

from __future__ import annotations

import argparse
import json
import math
import shutil
import subprocess
from dataclasses import dataclass, fields
from pathlib import Path


@dataclass(frozen=True)
class Design:
    panel_width: float
    panel_thickness: float
    width_clearance_each_side: float
    thickness_clearance_total: float
    base_depth: float
    base_thickness: float
    wall_thickness: float
    back_height: float
    front_height: float
    end_margin: float
    mount_hole_diameter: float
    mount_hole_edge_inset: float
    mount_hole_y: float

    @property
    def channel_width(self) -> float:
        return self.panel_thickness + self.thickness_clearance_total

    @property
    def base_width(self) -> float:
        return self.panel_width + 2 * self.width_clearance_each_side + 2 * self.end_margin

    @property
    def front_y(self) -> float:
        return self.base_depth - 2 * self.wall_thickness - self.channel_width

    def validate(self) -> None:
        for field in fields(self):
            value = getattr(self, field.name)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"{field.name} must be a finite number")
            if value <= 0:
                raise ValueError(f"{field.name} must be positive")

        if self.base_thickness < 3 or self.wall_thickness < 2:
            raise ValueError("base thickness must be >= 3 mm and wall thickness >= 2 mm")
        if self.front_height >= self.back_height:
            raise ValueError("front wall must be lower than back wall for panel access")
        if self.end_margin < self.wall_thickness:
            raise ValueError("end margin must support the channel end stops")
        if self.front_y < self.wall_thickness:
            raise ValueError("base is too shallow for the channel and walls")

        radius = self.mount_hole_diameter / 2
        edge = self.mount_hole_edge_inset
        if edge - radius < self.wall_thickness or self.base_width - 2 * edge < self.mount_hole_diameter + 2 * self.wall_thickness:
            raise ValueError("mounting holes need an edge margin and must not overlap")
        if self.mount_hole_y - radius < self.wall_thickness:
            raise ValueError("mounting holes are too close to the front edge")
        if self.mount_hole_y + radius + self.wall_thickness > self.front_y:
            raise ValueError("mounting holes must clear the panel channel")


def load_design(path: Path) -> Design:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("configuration must be a JSON object")
    expected = {field.name for field in fields(Design)}
    missing, extra = expected - data.keys(), data.keys() - expected
    if missing or extra:
        raise ValueError(f"configuration keys mismatch; missing={sorted(missing)}, extra={sorted(extra)}")
    design = Design(**data)
    design.validate()
    return design


def scad_parameters(design: Design) -> str:
    return "// Generated by build.py; edit the JSON configuration instead.\n" + "\n".join(
        f"{field.name} = {format(getattr(design, field.name), '.12g')};"
        for field in fields(design)
    ) + "\n"


def report(design: Design) -> dict[str, float | list[float]]:
    return {
        "base_width_mm": design.base_width,
        "base_depth_mm": design.base_depth,
        "channel_width_mm": design.channel_width,
        "channel_length_mm": design.panel_width + 2 * design.width_clearance_each_side,
        "mount_hole_centres_x_mm": [design.mount_hole_edge_inset, design.base_width - design.mount_hole_edge_inset],
        "mount_hole_y_mm": design.mount_hole_y,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path)
    parser.add_argument("--out", type=Path, default=Path("build"))
    parser.add_argument("--check", action="store_true", help="validate only; do not write files")
    parser.add_argument("--render", action="store_true", help="export STL with OpenSCAD")
    args = parser.parse_args()
    if args.check and args.render:
        parser.error("--check and --render cannot be combined")
    design = load_design(args.config)
    if args.check:
        print(json.dumps(report(design), indent=2))
        return

    root = Path(__file__).resolve().parent
    args.out.mkdir(parents=True, exist_ok=True)
    params = root / "cad" / "generated_params.scad"
    params.write_text(scad_parameters(design), encoding="utf-8")
    (args.out / "dimensions.json").write_text(json.dumps(report(design), indent=2) + "\n", encoding="utf-8")
    if args.render:
        openscad = shutil.which("openscad")
        if openscad is None:
            raise RuntimeError("OpenSCAD is not installed; parameters and report were written")
        subprocess.run([openscad, "-o", str(args.out / "sign-holder.stl"), str(root / "cad" / "sign_holder.scad")], check=True)
    print(f"Validated design; wrote {params} and {args.out / 'dimensions.json'}")


if __name__ == "__main__":
    main()
